/**
 * Returns the list of Academic Colleges offered on a given campus (for Students).
 */
export function getCollegesForCampus(campusSlug) {
  const entry = CHMSU_CAMPUS_DIRECTORY[campusSlug];
  if (!entry) return [];
  return Object.keys(entry.academicColleges);
}

/**
 * Returns the list of Degree Programs offered under a given College on a campus (for Students).
 */
export function getProgramsForCollege(campusSlug, collegeName) {
  const entry = CHMSU_CAMPUS_DIRECTORY[campusSlug];
  if (!entry || !collegeName) return [];
  return entry.academicColleges[collegeName] ?? [];
}

/**
 * Returns the list of Office Categories for a given campus (for Faculty, Staff, RMO).
 */
export function getOfficeCategoriesForCampus(campusSlug) {
  const entry = CHMSU_CAMPUS_DIRECTORY[campusSlug];
  if (!entry) return [];
  return Object.keys(entry.officeCategories);
}

/**
 * Returns the list of Offices under a given Office Category on a campus (for Faculty, Staff, RMO).
 */
export function getOfficesForCategory(campusSlug, categoryName) {
  const entry = CHMSU_CAMPUS_DIRECTORY[campusSlug];
  if (!entry || !categoryName) return [];
  return entry.officeCategories[categoryName] ?? [];
}

/**
 * Returns grouped Destination Office options for a given campus slug
 * (used by DocumentRegisterPanel, MyDocumentsClient, and OfficeScannerClient).
 */
export function getDestinationOfficesForCampus(campusSlug) {
  const entry = CHMSU_CAMPUS_DIRECTORY[campusSlug];
  if (!entry) return [];

  return Object.entries(entry.officeCategories).map(
    ([categoryName, offices]) => ({
      label: categoryName,
      options: offices,
    })
  );
}

export function getAllDestinationOfficesForCampus(campusSlug) {
  return getDestinationOfficesForCampus(campusSlug).flatMap((g) => g.options);
}

/**
 * Matches a staff member profile against a selected Destination Office dropdown value.
 */
export function matchesDestinationOffice(staffMember, selectedDestinationOffice) {
  const target = String(selectedDestinationOffice ?? "").trim().toLowerCase();
  if (!target || !staffMember) return false;

  const dept = String(staffMember.department ?? "").trim().toLowerCase();
  const office = String(staffMember.office_location ?? "").trim().toLowerCase();

  if (office && office === target) return true;
  if (dept && dept === target) return true;
  if (dept && office && `${dept} — ${office}` === target) return true;

  if (target.includes(" — ")) {
    const [targetDept, targetSub] = target.split(" — ").map((s) => s.trim());
    if (dept && office && dept === targetDept && office === targetSub) {
      return true;
    }
  }

  return false;
}
